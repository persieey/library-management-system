// SeedBooks ใส่ข้อมูลหนังสือตัวอย่างลงฐานข้อมูลเมื่อยังไม่มีข้อมูลเลย
func SeedBooks(db *gorm.DB) error {
	var count int64
	// เช็คว่ามีข้อมูลหนังสือในระบบหรือยัง
	if err := db.Model(&models.Book{}).Count(&count).Error; err != nil {
		return err
	}
	// ถ้ามีข้อมูลอยู่แล้วให้ข้ามไปเลย ป้องกันการ insert ข้อมูลซ้ำ
	if count > 0 {
		return nil
	}

	// บันทึกข้อมูล sampleBooks ลงในตาราง books
	if err := db.Create(&sampleBooks).Error; err != nil {
		return err
	}

	log.Printf("ใส่ข้อมูลหนังสือตัวอย่าง %d รายการแล้ว", len(sampleBooks))
	return nil
}
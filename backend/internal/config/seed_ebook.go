// SeedEbooks ใส่ E-Book ตัวอย่างลงฐานข้อมูลเมื่อยังไม่มีข้อมูลเลย
//
// เช็คก่อนเสมอว่ามีอยู่แล้วหรือยัง เพราะฟังก์ชันนี้ทำงานทุกครั้งที่รันเซิร์ฟเวอร์
// ถ้าไม่เช็คจะได้ข้อมูลซ้ำเพิ่มขึ้นเรื่อยๆ
func SeedEbooks(db *gorm.DB) error {
	var count int64
	if err := db.Model(&models.Ebook{}).Count(&count).Error; err != nil {
		return err
	}
	if count > 0 {
		return nil
	}

	// ผูกกับพนักงานคนแรกที่มีในระบบ ถ้ายังไม่มีก็ปล่อยว่างไว้
	var employee models.Employee
	var employeeID *uint
	if err := db.First(&employee).Error; err == nil {
		employeeID = &employee.EmployeeID
	}

	items := make([]models.Ebook, len(sampleEbooks))
	copy(items, sampleEbooks)
	for i := range items {
		items[i].EmployeeID = employeeID
	}

	if err := db.Create(&items).Error; err != nil {
		return err
	}

	log.Printf("ใส่ E-Book ตัวอย่าง %d รายการแล้ว", len(items))
	return nil
}